total_score = 0
questions = [
    "1. კოდის გამართულობა და სტრუქტურის სისუფთავე (0-12): ",
    "2. მასალის ლოგიკური გააზრების დონე (0-12): ",
    "3. სტუდენტის მონდომება და ჯანსაღი იუმორი (0-12): "
]

print("--- დაგვიანებული დავალების საინსპექციო ოქმი ---")
print("გთხოვთ, შეაფასოთ სამი საკვანძო კრიტერიუმი 0-დან 12-მდე შკალით:")

for i in questions:
    score = int(input(i))
    total_score += score

print("\n---------------- შედეგი ----------------")
print(f"საბოლოო შეფასება: {total_score} / 36")

if total_score >= 30:
    print("ვერდიქტი: კოდი დედლაინზე ძლიერი აღმოჩნდა.დავალება მიღებულია!")
    print("P.S. დაგვიანებისთვის ბოდიში, დროის მენეჯმენტი აუცილებლად გამოსწორდება.")
elif total_score >= 20:
    print("ვერდიქტი: ოპტიმიზმის ზღვარზე ვართ — გადაწყვეტილება ექსპერტზეა.")
else:
    print("ვერდიქტი: მკაცრი, მაგრამ სამართლიანი. სტუდენტი მიდის დამატებით სამუშაოზე.")